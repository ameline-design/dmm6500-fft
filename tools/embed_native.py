#!/usr/bin/env python3
"""Turn the built PPC image and its relocation table into a TSP module.

Writes tsp/native_code.tsp, which the packager concatenates after native_link.tsp (which
creates the fftsa.nl table) and before spectrum_app.tsp (which reads nl.ready).

Both blobs go in as base64, each with a _LEN beside it, and fftsa.nl._b64decode turns them
back into bytes once at startup. ki.memwrite takes its length from lua_strlen rather than
strlen, so the NUL bytes a binary is full of survive a Lua string whichever encoding is
used; what decides it is size. Lua 5.0.2 has no \\xNN escape, which leaves decimal as the
only literal form for raw bytes, at 4.00 characters a byte against base64's 1.37.

Each blob is a table of string literals joined with table.concat rather than one literal.
Two reasons, both about what the instrument's loader will accept:

  - nothing establishes that a line of tens of thousands of characters survives the script
    path. Pieces of B64_PIECE characters keep every line near 3 kB.
  - a chain of `..` instead would nest the expression 50 deep and Lua 5.0.2 bounds parser
    recursion (LUAI_MAXCCALLS); table.concat has no such limit.

B64_PIECE is a multiple of 4, so each piece is a whole number of base64 quanta and
concatenating the pieces gives the same string as encoding the whole blob at once.

csrc/tools/check_b64.py gates both ends: the emitted text against Python's base64 of the
built binary, and the Lua decoder against the same bytes. See fwmem-NATIVEC.md.

    python3 tools/embed_native.py --build build-ppc
"""

import argparse
import base64
import os
import sys

B64_PIECE = 3072   # base64 characters per literal, a multiple of 4 so pieces concatenate


def lua_b64(data, var, piece=B64_PIECE):
    """`var` assigned from a table.concat of base64 literals, plus `var`_LEN.

    Four characters per three bytes, against four per byte for the decimal escapes
    ki.memwrite would otherwise need -- Lua 5.0.2 has no \\xNN. At 4.0 characters a byte a
    27 KB image is 109 KB of script source, which the instrument reads and parses at every
    app launch; this is about 1.37, and nl.init decodes it once.

    No '=' padding: the binary is padded to a multiple of three and the true length is
    emitted beside it, so the decoder is a flat four-to-three loop with no tail case. A
    decoder with a tail case is a decoder with a branch nothing exercises until the day the
    image length changes residue.

    Each piece is a whole number of base64 quanta, so concatenating them is the same string
    as encoding the whole blob.
    """
    pad = (3 - len(data) % 3) % 3
    text = base64.b64encode(data + b'\0' * pad).decode('ascii')
    assert '=' not in text, 'padded to a multiple of three, so there can be no ='
    out = ['%s_LEN = %d' % (var, len(data)),
           '%s = table.concat({' % var]
    for i in range(0, len(text), piece):
        out.append("'%s'," % text[i:i + piece])
    out.append('})')
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--build', default='build-ppc',
                    help='directory holding dsp_native.bin and dsp_native_reloc.lua')
    ap.add_argument('--out', default='tsp/native_code.tsp')
    args = ap.parse_args()

    bin_path = os.path.join(args.build, 'dsp_native.bin')
    lua_path = os.path.join(args.build, 'dsp_native_reloc.lua')
    for p in (bin_path, lua_path):
        if not os.path.exists(p):
            sys.exit('missing %s: build the dsp_native_bin target first' % p)

    with open(bin_path, 'rb') as fh:
        image = fh.read()
    with open(lua_path) as fh:
        reloc = fh.read()

    # The generated relocation module assigns into fftsa.nl, so it has to come after the
    # module that creates that table. Checked rather than assumed: a stray assignment to
    # a nil table is a load-time error that would take the whole app down.
    if 'fftsa.nl' not in reloc:
        sys.exit('%s does not assign into fftsa.nl; check emit_reloc.py' % lua_path)

    lines = [
        '-- native_code.tsp -- generated by tools/embed_native.py; do not edit.',
        '--',
        '-- The compiled PowerPC image and the relocation table that places it at its load',
        '-- address. Concatenated after native_link.tsp, which creates fftsa.nl, and before',
        '-- spectrum_app.tsp, which reads nl.ready.',
        '--',
        '-- %d bytes of image, %d relocation bytes.' % (len(image), 0),
        '',
    ]
    lines.extend(lua_b64(image, 'fftsa.nl._DSP_CODE_B64'))
    lines.append('')
    lines.append('-- Relocation table and the target struct sizes, from emit_reloc.py.')
    # The generated file assigns _DSP_RELOC as one literal; re-emit it in pieces for the
    # same line-length reason, and pass the scalar assignments through unchanged.
    reloc_bytes = None
    passthrough = []
    for line in reloc.splitlines():
        if line.startswith('fftsa.nl._DSP_RELOC = '):
            lit = line.split(" = ", 1)[1].strip()
            assert lit[0] == "'" and lit[-1] == "'", 'unexpected literal form'
            body = lit[1:-1]
            # Decode the \NNN escapes back to bytes.
            vals = [int(body[i + 1:i + 4]) for i in range(0, len(body), 4)]
            reloc_bytes = bytes(vals)
        elif line.startswith('fftsa.nl.') or line.startswith('--'):
            passthrough.append(line)
    if reloc_bytes is None:
        sys.exit('no _DSP_RELOC assignment found in %s' % lua_path)

    lines.extend(lua_b64(reloc_bytes, 'fftsa.nl._DSP_RELOC_B64'))
    lines.append('')
    lines.extend(passthrough)
    lines.append('')

    lines[6] = ('-- %d bytes of image, %d relocation bytes (%d entries).'
                % (len(image), len(reloc_bytes), len(reloc_bytes) // 9))

    body = '\n'.join(lines) + '\n'
    with open(args.out, 'w') as fh:
        fh.write(body)

    longest = max(len(x) for x in lines)
    blob = len(image) + len(reloc_bytes)
    print('%s' % args.out)
    print('  image   %7d bytes' % len(image))
    print('  relocs  %7d bytes, %d entries' % (len(reloc_bytes), len(reloc_bytes) // 9))
    print('  module  %7d bytes, longest line %d  (%.2f characters a byte against %.2f '
          'for decimal escapes)'
          % (len(body), longest, float(len(body)) / blob, 4.0))


if __name__ == '__main__':
    main()
