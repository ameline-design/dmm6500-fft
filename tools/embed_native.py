#!/usr/bin/env python3
"""Turn the built PPC image and its relocation table into a TSP module.

Writes tsp/native_code.tsp, which the packager concatenates after native_link.tsp (which
creates the fftsa.nl table) and before spectrum_app.tsp (which reads nl.ready).

The image is emitted as a table of string literals joined with table.concat rather than
one long literal. Two reasons, both about what the instrument's loader will accept:

  - 25 KB of \\NNN escapes is about 103,000 characters, and nothing establishes that a
    line that long survives the script path. Pieces keep every line under 8 KB.
  - A chain of `..` instead would nest the expression 50 deep and Lua 5.0.2 bounds
    parser recursion (LUAI_MAXCCALLS); table.concat has no such limit.

Decimal escapes because ki.memwrite takes its length from lua_strlen rather than strlen,
so the embedded NUL bytes a binary is full of are copied faithfully. Lua 5.0.2 has no
\\xNN escape, so decimal is also the only option. See fwmem-DISPATCH.md.

    python3 tools/embed_native.py --build build-ppc
"""

import argparse
import os
import sys

PIECE = 2048  # bytes of binary per Lua string literal


def lua_pieces(data, var, piece=PIECE):
    """`var` assigned from a table.concat of decimal-escape literals.

    A table constructor rather than a named temporary: tools/lint_tsp.py refuses a bare
    global assignment, and it reads the source textually, so even `local _p` followed by
    `_p = nil` trips it. Nothing is named here, so there is nothing to refuse.
    """
    out = ['%s = table.concat({' % var]
    for i in range(0, len(data), piece):
        lit = ''.join('\\%03d' % b for b in data[i:i + piece])
        out.append("'%s'," % lit)
    out.append('})')
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--build', default='build-ppc',
                    help='directory holding dsp_native.bin and dsp_native_reloc.lua')
    ap.add_argument('--out', default='tsp/native_code.tsp')
    args = ap.parse_args()

    bin_path = os.path.join(args.build, 'dsp_native.bin')
    lua_path = os.path.join(args.build, 'dsp_native_reloc.lua')
    for p in (bin_path, lua_path):
        if not os.path.exists(p):
            sys.exit('missing %s: build the dsp_native_bin target first' % p)

    with open(bin_path, 'rb') as fh:
        image = fh.read()
    with open(lua_path) as fh:
        reloc = fh.read()

    # The generated relocation module assigns into fftsa.nl, so it has to come after the
    # module that creates that table. Checked rather than assumed: a stray assignment to
    # a nil table is a load-time error that would take the whole app down.
    if 'fftsa.nl' not in reloc:
        sys.exit('%s does not assign into fftsa.nl; check emit_reloc.py' % lua_path)

    lines = [
        '-- native_code.tsp -- generated by tools/embed_native.py; do not edit.',
        '--',
        '-- The compiled PowerPC image and the relocation table that places it at its load',
        '-- address. Concatenated after native_link.tsp, which creates fftsa.nl, and before',
        '-- spectrum_app.tsp, which reads nl.ready.',
        '--',
        '-- %d bytes of image, %d relocation bytes.' % (len(image), 0),
        '',
    ]
    lines.extend(lua_pieces(image, 'fftsa.nl._DSP_CODE'))
    lines.append('')
    lines.append('-- Relocation table and the target struct sizes, from emit_reloc.py.')
    # The generated file assigns _DSP_RELOC as one literal; re-emit it in pieces for the
    # same line-length reason, and pass the scalar assignments through unchanged.
    reloc_bytes = None
    passthrough = []
    for line in reloc.splitlines():
        if line.startswith('fftsa.nl._DSP_RELOC = '):
            lit = line.split(" = ", 1)[1].strip()
            assert lit[0] == "'" and lit[-1] == "'", 'unexpected literal form'
            body = lit[1:-1]
            # Decode the \NNN escapes back to bytes.
            vals = [int(body[i + 1:i + 4]) for i in range(0, len(body), 4)]
            reloc_bytes = bytes(vals)
        elif line.startswith('fftsa.nl.') or line.startswith('--'):
            passthrough.append(line)
    if reloc_bytes is None:
        sys.exit('no _DSP_RELOC assignment found in %s' % lua_path)

    lines.extend(lua_pieces(reloc_bytes, 'fftsa.nl._DSP_RELOC'))
    lines.append('')
    lines.extend(passthrough)
    lines.append('')

    lines[6] = ('-- %d bytes of image, %d relocation bytes (%d entries).'
                % (len(image), len(reloc_bytes), len(reloc_bytes) // 9))

    body = '\n'.join(lines) + '\n'
    with open(args.out, 'w') as fh:
        fh.write(body)

    longest = max(len(x) for x in lines)
    print('%s' % args.out)
    print('  image   %7d bytes -> %d literal(s)'
          % (len(image), (len(image) + PIECE - 1) // PIECE))
    print('  relocs  %7d bytes -> %d entries' % (len(reloc_bytes), len(reloc_bytes) // 9))
    print('  module  %7d bytes, longest line %d' % (len(body), longest))


if __name__ == '__main__':
    main()
